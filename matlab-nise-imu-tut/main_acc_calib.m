close all
clear all

% Load transformations need by this script, fallback to identity if not found.
vars = {'T_acc_0'};
for k=1:length(vars)
    if ~isfile([vars{k} '.mat'])
        eval([vars{k} ' = eye(4);']);
        continue;
    end
    load(vars{k});
end

regexFile = '*/data/acc*.mat';
files = dir(regexFile);

refPointInd = 100;
acc_raw = [];

for k=1:length(files)
    file = files(k);
    name = file.name;
    path = file.folder;
    fileNamePath = [path '/' name];
    disp(['Load experiment: ' name]);
    temp = load(fileNamePath);
    expt(k) = temp.expt;
    acc_raw = [acc_raw, expt(k).imu.acc];
end

[M,w,R,G] = accCalib(acc_raw);

T_e_0 = eye(4);

%??????????????????????????????????????????????????????????????????????????
% The tranformation T_e_0 matrix to represent the coordinate system of
% the ellipsoid wrt to the base frame 0.
%
% Use R and w of the calibration to compose this transfomration matrix.
T_e_0(1:3,1:3) = R;
T_e_0(1:3,4) = w;
%??????????????????????????????????????????????????????????????????????????

Tm = eye(4);

%??????????????????????????????????????????????????????????????????????????
% Compute the homogeneous model matrix
% - Make sure that Tm does not rotate the coordinate axes
% - Tm should approximately be a diagonal matrix
% - Use G and R to compose this matrix
Tm(1:3,1:3) = G;
%??????????????????????????????????????????????????????????????????????????

Tw = eye(4);

%??????????????????????????????????????????????????????????????????????????
% Compute the homogeneous offset matrix
% - Use w to compose this matrix
Tw(1:3,4) = -w;
%??????????????????????????????????????????????????????????????????????????

T_raw_acc = Tm * Tw;

acc_raw_hom = [acc_raw; ones(1,size(acc_raw,2))];
acc_calib_hom = T_raw_acc * acc_raw_hom;
acc_calib = acc_calib_hom(1:3,:);

disp('Transform acc coordinate system to coordinate system 0:');
disp('T_acc_0 =')
disp(T_acc_0);

regexFile = 'data/acc*.mat';
files = dir(regexFile);
acc_raw = [];

for k=1:length(files)
    temp = load([files(k).folder '/' files(k).name]);
    expt(k) = temp.expt;
    acc_raw(k).name = expt(k).name;
    acc_raw(k).mean = mean(expt(k).imu.acc,2);
end

names = {'accXp','accXn','accYp','accYn','accZp','accZn'};
descr = {'+x','-x','+y','-y','+z','-z'};
name2el = @(s,name) s(strcmp({s(:).name},name));

for k=1:length(names)
    el = name2el(acc_raw,names{k});
    acc_raw_mean = el.mean;

    %??????????????????????????????????????????????????????????????????????
    % Use T_acc_0 and T_raw_acc to calibrate the measurements and
    % transform them to the base coordinate frame 0.
    %
    % Expand acc_raw to homogeneous coordinates such that
    % isequal(size(acc_raw),[4 1]) == true
    % Transform acc_raw_mean to a_0
    acc_raw_mean_hom = [acc_raw_mean; 0];
    a_0_hom = T_acc_0 * T_raw_acc * acc_raw_mean_hom;
    a_0 = a_0_hom(1:3);
    %??????????????????????????????????????????????????????????????????????

    disp(['Calibrated gravitational acceleration in ' descr{k} ':']);
    disp(a_0)
end

save('T_raw_acc.mat','T_raw_acc');
