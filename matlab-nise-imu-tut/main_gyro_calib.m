files = dir(regexFile);

file = files(1);
name = file.name;
path = file.folder;
fileNamePath = [path '/' name];

temp = load(fileNamePath);
expt = temp.expt;
imu = expt.imu;

t = imu.t;



Tm = eye(4);

%??????????????????????????????????????????????????????????????????????????
%   Manually calibrate the gyro gain by looking at figure 2

Tm(1:3,1:3) = diag([1 1 1]);

%??????????????????????????????????????????????????????????????????????????



T_raw_gyro = eye(4);

%??????????????????????????????????????????????????????????????????????????
%   Compose the homogeneous calibration matrix T_raw_gyro for the gyroscope
%
%   Use Tm and Tw_raw_gyro. First apply the translation, then the scaling.
%


%??????????????????????????????????????????????????????????????????????????




acc_raw = imu.acc;

%??????????????????????????????????????????????????????????????????????????
%   Calibrate acc_raw and transform wrt coordinate system 0
%    
%   Use T_acc_0 and T_raw_acc

acc_0 = acc_raw;
%??????????????????????????????????????????????????????????????????????????



gyro_raw = imu.gyro;

%??????????????????????????????????????????????????????????????????????????
%   Calibrate gyro_raw and transform wrt coordinate system 0
%    
%   Use T_gyro_0 and T_raw_gyro
%

gyro_0 = gyro_raw;
%??????????????????????????????????????????????????????????????????????????



mag_raw = imu.mag;

%??????????????????????????????????????????????????????????????????????????
%   Calibrate mag_raw and transform wrt coordinate system 0
%    
%   Use T_mag_0 and T_raw_mag
%

mag_0 = mag_raw;
%??????????????????????????????????????????????????????????????????????????



%??????????????????????????????????????????????????????????????????????????
%   Integrate gyro_0 using 'cumtrapz' to get the roll, pitch, yaw angles in
%   degrees.

phi_gyro = zeros(1,size(gyro_0,2));
theta_gyro = zeros(1,size(gyro_0,2));
psi_gyro = zeros(1,size(gyro_0,2));
%??????????????????????????????????????????????????????????????????????????



%??????????????????????????????????????????????????????????????????????????
%   Exloit geometry and use acc_0 to calculate the roll, pitch, yaw angles
%   in degrees.
%
%   Only consider the three conditions of the three supplied experiments.
%   Two experiments align the z axis of the base frame to the negative 
%   gravitational acceleration, and one the x axis.
%

phi_acc = zeros(1,size(acc_0,2));
theta_acc = zeros(1,size(acc_0,2));
psi_acc = zeros(1,size(acc_0,2));
%??????????????????????????????????????????????????????????????????????????



phi_mag = zeros(1,size(mag_0,2));
theta_mag = zeros(1,size(mag_0,2));

%??????????????????????????????????????????????????????????????????????????
%   Exloit geometry and use mag_0 to calculate the psi angle in degrees
%
%   Only compute the psi angle in degrees.
%

psi_mag = zeros(1,size(mag_0,2));

%??????????????????????????????????????????????????????????????????????????


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Calibrated wrt coordinate system 0
figure

titleStr={'Acc. calib.','Gyro. calib.','Mag. calib.'};

yLabelStr={
    '{\boldmath$a$} [$\mathrm{m/s^2}$]',...
    '{\boldmath$\omega$} [$\mathrm{deg/s}$]',...
    '{\boldmath$b$} [$\mathrm{normalized}$]',...
    };

meas_0={acc_0,gyro_0,mag_0};



for k=1:3

    subplot(1,3,k)
    hold on
    grid on
    set(gca,'TickLabelInterpreter', 'latex');
    set(gca,'FontSize',10);
    
    leg = [];
    
    p = meas_0{k};
    
    x = t;
    y = p(1,:);
    h = plot(x,y);
    leg(end+1).h    = h;
    leg(end).label  = '$x$';
    
    x = t;
    y = p(2,:);
    h = plot(x,y);
    leg(end+1).h    = h;
    leg(end).label  = '$y$';
    
    x = t;
    y = p(3,:);
    h = plot(x,y);
    leg(end+1).h    = h;
    leg(end).label  = '$z$';
    
    h = xlabel('$t$ [$\mathrm{s}$]');
    set(h,'Interpreter','latex');

    h = ylabel(yLabelStr{k});
    set(h,'Interpreter','latex');
    
    h = legend([leg(:).h], {leg(:).label});
    set(h,'Interpreter','latex');
    set(h,'FontSize',10);
    set(h,'Location','NorthEast');
    
    
    h = title(['\textbf{' titleStr{k} '}']);
    set(h,'Interpreter','latex');
    set(h,'FontSize',12);

end


