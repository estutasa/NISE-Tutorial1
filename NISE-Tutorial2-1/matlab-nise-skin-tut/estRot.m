% Estimate the rotation R_a_b between a set of vectors in the 
%   coordinate system a and coordinate system b. 
%   R_a_b maps a to b via b = R_a_b * a.
%
%   [R_a_b] = estRot(acc_a,acc_b)
%
%   R_a_b = rotation from coorinate system a to coordinate system b
%
function [R_a_b] = estRot(acc_a,acc_b)

A = acc_a;
B = acc_b;

R_a_b = eye(3);

%??????????????????????????????????????????????????????????????????????????
%   Implement the solution to the Procrustes problem such that A * R = B
%
%   

M = B * A.'; % M = B*A^T
[U,~,V] = svd(M); % signular value decomposition to get rotation and stretching matrices
D = eye(3);
D(3,3) = sign(det(U*V.')); % forcing the determinant of R to be 1

% Rotation from frame a to frame b: b ≈ R * a
R_a_b = U * D * V.'; % R = UDV^T


