% Load transformations need by this script, fallback to identity if not
% found.
vars = {'T_acc_0'};

for k=1:length(vars)
    if ~isfile([vars{k} '.mat'])
        eval([vars{k} ' = eye(4);']);
        continue;
    end
    load(vars{k});
end


regexFile = 'data/*acc*.mat';

files = dir(regexFile);

% Use this point to check if the orientation is correct.
refPointInd = 11436;

acc_raw = [];

for k=1:length(files)
    file = files(k);
    name = file.name;
    path = file.folder;
    fileNamePath = [path '/' name];
    
    disp(['Load experiment: ' name]);
    
    temp = load(fileNamePath);
    expt(k) = temp.expt;
    
    acc_raw = [acc_raw, expt(k).imu.acc];
end

% Use all the measurements and compute the model matrix and the offset.
[M,w,R,G] = accCalib(acc_raw);

disp('Offset:');
disp('w =');
disp(w);

disp('Model matrix:');
disp('M =');
disp(M);


disp('Rotation matrix:');
disp('R =');
disp(R);

disp('Gain matrix:');
disp('G =');
disp(G);


T_e_0 = eye(4);

%??????????????????????????????????????????????????????????????????????????
%   The tranformation T_e_0 matrix to represent the coordinate system of 
%   the ellipsoid wrt to the base frame 0. 
%
%   Use R and w of the calibration to compose this transfomration matrix.

% slides: E = [R b][0, 1]
T_e_0(1:3,1:3) = R'; % use inverse/transpose here because R in calibration 
% maps  base/sensor frame --> ellipsoid frame, but T_e_0 maps must axes of 
% ellipsoid frame --> base frame
T_e_0(1:3,4) = w; % b is position of ellipsoid orign frame in base frame, which is w

%??????????????????????????????????????????????????????????????????????????


disp('Ellipsoid wrt. base frame:');
disp('T_e_0 =');
disp(T_e_0);



%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous model matrix 
%   - Make sure that Tm does not rotate the coordinate axes
%   - Tm should approximately be a diagonal matrix
%   - Use G and R to compose this matrix

Tm = eye(4);
Tm(1:3,1:3) = R' * G * R; % rotate into ellipsoid frame to scale there, 
% but then rotate back to express it in base frame

%??????????????????????????????????????????????????????????????????????????

disp('Homogeneous model matrix:');
disp('Tm =');
disp(Tm);

%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous offset matrix
%   - Use w to compose this matrix
%   
%
Tw = eye(4);
Tw(1:3,4) = -w; % because w is the ellipsoid center; therefore, offset 
% must be corrected by -w

%??????????????????????????????????????????????????????????????????????????

disp('Homogeneous offset matrix:');
disp('Tw =');
disp(Tw);


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous calibration matrix
%   - first remove the offset from the measurements
%   - then compensate the gains of the measurements

T_raw_acc = Tm * Tw; % translation first (rightmost), then scaling!

%??????????????????????????????????????????????????????????????????????????


%??????????????????????????????????????????????????????????????????????????
%   Compute the calibrated measurements using T_raw_acc
%   - Extend acc_raw to homogeneous coordinates such that 
%        isequal(size(acc_raw),[4 N]) == true
%   - Transform acc_raw to acc_calib using T_raw_acc
%
%   NOTE: The error of the calibrated acc will be at least an order of
%   magnitude less than the uncalibrated acc.

% extending acc_raw to homogeneous coordinates (4 x N)
N = size(acc_raw,2);
acc_raw_h = [acc_raw(1:3,:); ones(1,N)];

% equation 1:  accX (this is calib) = T_raw_acc * accX_raw
acc_calib_h = T_raw_acc * acc_raw_h;

% back to 3 x N
acc_calib = acc_calib_h(1:3,:);

%??????????????????????????????????????????????????????????????????????????


% Error of uncalibrated acc
n = vecnorm(acc_raw(1:3,:));
err = sum(n)/length(n)-1;

disp('Error of uncalibrated acc:');
disp(['err = ' num2str(err)]);
fprintf('\n');



% Error of calibration
n = vecnorm(acc_calib(1:3,:));
err = sum(n)/length(n)-1;

disp('Error of calibration:');
disp(['err = ' num2str(err)]);
fprintf('\n');




