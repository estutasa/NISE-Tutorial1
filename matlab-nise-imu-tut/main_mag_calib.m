close all
clear all

regexFile = 'data/*mag*.mat';

files = dir(regexFile);

% Use this point to check if the orientation is correct.
refPointInd = 553;

mag_raw = [];

for k=1:length(files)
    file = files(k);
    name = file.name;
    path = file.folder;
    fileNamePath = [path '/' name];
    
    disp(['Load experiment: ' name]);
    
    temp = load(fileNamePath);
    expt(k) = temp.expt;
    
    mag_raw = [mag_raw, expt(k).imu.mag];
end

% Use all the measurements and compute the model matrix and the offset.
[M,w,R,G] = magCalib(mag_raw);

disp('Offset:');
disp('w =');
disp(w);

disp('Model matrix:');
disp('M =');
disp(M);

disp('Rotation matrix:');
disp('R =');
disp(R);

disp('Gain matrix:');
disp('G =');
disp(G);


T_e_0 = eye(4);

%??????????????????????????????????????????????????????????????????????????
%   The tranformation T_e_0 matrix to represent the coordinate system of 
%   the ellipsoid wrt to the base frame 0. 
%
%   Use R and w of the calibration to compose this transfomration matrix.

T_e_0(1:3,1:3) = eye(3);
T_e_0(1:3,4) = zeros(3,1);

%??????????????????????????????????????????????????????????????????????????


disp('Ellipsoid wrt. base frame:');
disp('T_e_0 =');
disp(T_e_0);


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous model matrix 
%   - Make sure that Tm does not rotate the coordinate axes
%   - Tm should approximately be a diagonal matrix
%   - Use G and R to compose this matrix

Tm = eye(4);
Tm(1:3,1:3) = eye(3);

%??????????????????????????????????????????????????????????????????????????


disp('Homogeneous model matrix:');
disp('Tm =');
disp(Tm);


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous offset matrix
%   - Use w to compose this matrix
%   
%
Tw = eye(4);
Tw(1:3,4) = zeros(3,1);

%??????????????????????????????????????????????????????????????????????????

disp('Homogeneous offset matrix:');
disp('Tw =');
disp(Tw);


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous calibration matrix
%   - first remove the offset from the measurements
%   - then compensate the gains of the measurements

T_raw_mag = eye(4);

%??????????????????????????????????????????????????????????????????????????



%??????????????????????????????????????????????????????????????????????????
%   Compute the calibrated measurements using T_raw_mag
%   - Extend mag_raw to homogeneous coordinates such that 
%        isequal(size(mag_raw),[4 N]) == true
%   - Transform mag_raw to mag_calib using T_raw_mag
%
%   NOTE: The error of the calibrated acc will be at least an order of
%   magnitude less.

mag_calib = mag_raw;

%??????????????????????????????????????????????????????????????????????????


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous model matrix using only the average gain on all
%   axes

% Homogeneous model matrix for average gain compensation
Tm_avg = eye(4);

%??????????????????????????????????????????????????????????????????????????

disp('Homogeneous model matrix with average gains:');
disp('Tm_avg =');
disp(Tm_avg);


%??????????????????????????????????????????????????????????????????????????
%   Compute the homogeneous calibration matrix
%   - first remove the offset from the measurements
%   - then compensate the gains of the measurements

Tavg_raw_mag = eye(4);

%??????????????????????????????????????????????????????????????????????????


%??????????????????????????????????????????????????????????????????????????
%   Compute the calibrated measurements using Tavg_raw_mag
%   - Transform mag_raw to mag_avg_calib using Tavg_raw_mag

mag_avg_calib = mag_raw;

%??????????????????????????????????????????????????????????????????????????


% Error of calibration
n = vecnorm(mag_calib(1:3,:));
err = sum(n)/length(n)-1;

disp('Error of calibration:');
disp(['err = ' num2str(err)]);
fprintf('\n');


% Error of calibration with average gains
n = vecnorm(mag_avg_calib(1:3,:));
err = sum(n)/length(n)-1;

disp('Error of calibration (avg. gains):');
disp(['err = ' num2str(err)]);
fprintf('\n');


