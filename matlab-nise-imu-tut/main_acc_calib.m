% Load imu data with defined poses
regexFile = 'data/acc*.mat';
files = dir(regexFile);

acc_raw = [];

for k=1:length(files)
    file = files(k);
    name = file.name;
    path = file.folder;
    fileNamePath = [path '/' name];
    
    disp(['Load experiment: ' name]);
    
    temp = load(fileNamePath);
    expt(k) = temp.expt;

    acc_raw(k).name = expt(k).name;
    acc_raw(k).mean = mean(expt(k).imu.acc,2);

end

name2el = @(s,name) s(strcmp({s(:).name},name));

names = {'accXp','accXn','accYp','accYn','accZp','accZn'};
descr = {'+x','-x','+y','-y','+z','-z'};

for k=1:length(names)
    el = name2el(acc_raw,names{k});
    
    acc_raw_mean = el.mean;
    
    %??????????????????????????????????????????????????????????????????????
    %   Use T_acc_0 and T_raw_acc to calibrate the measurements and
    %   transform them to the base coordinate frame 0.

    % Expand acc_raw to homogeneous coordinates such that 
    %   isequal(size(acc_raw),[4 1]) == true
    
    % Transform acc_raw_mean to a_0


    x_raw = [acc_raw_mean; 1]; % expanding to 4x1
    x_acc = T_raw_acc * x_raw; % calibrate in accelerometer frame
    x_0 = T_acc_0 * x_acc; % rotate into base frame
    a_0 = x_0(1:3); % back to 3x1
    
    %??????????????????????????????????????????????????????????????????????
    
    str = ['Calibrated gravitational acceleration in ' descr{k} ':'];
    disp(str)
    disp(a_0)
end


