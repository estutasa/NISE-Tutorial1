        eval([vars{k} ' = eye(4);']);
        continue;
    end
    load(vars{k});
end

%??????????????????????????????????????????????????????????????????????????
%   Select the measurements you want to load. You need to check out all of
%   them to determine the three gains of gyroscope.
%

regexFile = 'data/imuExpt_gyro_x_top_z_2.mat';
